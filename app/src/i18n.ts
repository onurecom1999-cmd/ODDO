const LANG_KEY = 'oddo-lang';

// On the web the landing page and the app share an origin, so a language picked there carries over.
export function detectLang(): Lang {
  if (Platform.OS === 'web') {
    try {
      const saved = localStorage.getItem(LANG_KEY);
      if (saved && LANGS.includes(saved as Lang)) return saved as Lang;
    } catch {}
  }
  const locale = (Platform.OS === 'web' ? navigator.language : Intl.DateTimeFormat().resolvedOptions().locale) || 'en';
  const code = locale.slice(0, 2) as Lang;
  return LANGS.includes(code) ? code : 'en';
}

let current: Lang = 'de';

export function setLang(lang: Lang) {
  current = lang;
  if (Platform.OS === 'web') {
    try {
      localStorage.setItem(LANG_KEY, lang);
      document.documentElement.lang = lang;
    } catch {}
  }
}

export function getLang() {
  return current;
}

export function locale() {
  return { de: 'de-DE', tr: 'tr-TR', en: 'en-GB' }[current];
}

export function t(key: Key, vars?: Record<string, string | number>) {
  let text = DICTS[current][key] ?? de[key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.split(`{${k}}`).join(String(v));
  return text;
}
